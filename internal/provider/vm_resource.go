package provider

import (
	"context"
	"errors"
	"github.com/hashicorp/terraform-plugin-framework/attr"
	"github.com/hashicorp/terraform-plugin-framework/diag"
	"github.com/hashicorp/terraform-plugin-framework/path"
	"github.com/hashicorp/terraform-plugin-framework/resource"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/booldefault"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/boolplanmodifier"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/planmodifier"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/stringplanmodifier"
	"github.com/hashicorp/terraform-plugin-framework/types"
	"github.com/kybornos/terraform-provider-kybornos/internal/client"
)

var _ resource.Resource = (*VMResource)(nil)
var _ resource.ResourceWithConfigure = (*VMResource)(nil)
var _ resource.ResourceWithImportState = (*VMResource)(nil)
var interfaceObjectType = types.ObjectType{
	AttrTypes: map[string]attr.Type{
		"ip4":     types.StringType,
		"lladdr":  types.StringType,
		"primary": types.BoolType,
		"public":  types.BoolType,
	},
}

type VMResource struct{ c *client.Client }
type vmModel struct {
	ID         types.String `tfsdk:"id"`
	Hostname   types.String `tfsdk:"hostname"`
	VMName     types.String `tfsdk:"vm_name"`
	Size       types.String `tfsdk:"size"`
	CPU        types.Int64  `tfsdk:"cpu"`
	Memory     types.Int64  `tfsdk:"memory"`
	Disk       types.Int64  `tfsdk:"disk"`
	Public     types.Bool   `tfsdk:"public"`
	Interfaces types.List   `tfsdk:"interfaces"`
}

type interfaceModel struct {
	IP4     types.String `tfsdk:"ip4"`
	LLAddr  types.String `tfsdk:"lladdr"`
	Primary types.Bool   `tfsdk:"primary"`
	Public  types.Bool   `tfsdk:"public"`
}

func interfacesToList(ctx context.Context, interfaces []client.VMInterface) (types.List, diag.Diagnostics) {
	items := make([]interfaceModel, 0, len(interfaces))

	for _, iface := range interfaces {
		items = append(items, interfaceModel{
			IP4:     types.StringValue(iface.IP4),
			LLAddr:  types.StringValue(iface.LLAddr),
			Primary: types.BoolValue(iface.Primary),
			Public:  types.BoolValue(iface.Public),
		})
	}

	return types.ListValueFrom(ctx, interfaceObjectType, items)
}

func NewVMResource() resource.Resource { return &VMResource{} }
func (r *VMResource) Metadata(_ context.Context, _ resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = "kybornos_vm"
}
func (r *VMResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{Description: "A Kybornos virtual machine. Name/size changes replace the VM.", Attributes: map[string]schema.Attribute{
		"id": schema.StringAttribute{Computed: true, Description: "Stable VM identifier."},
		"hostname": schema.StringAttribute{
			Required:      true,
			Description:   "Hostname of the virtual machine.",
			PlanModifiers: []planmodifier.String{stringplanmodifier.RequiresReplace()},
		},
		"vm_name": schema.StringAttribute{
			Computed:      true,
			Description:   "Unique VM name generated by Kybornos",
			PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
		},
		"size": schema.StringAttribute{Required: true, PlanModifiers: []planmodifier.String{stringplanmodifier.RequiresReplace()}},
		"cpu": schema.Int64Attribute{
			Computed: true,
		},
		"memory": schema.Int64Attribute{
			Computed: true,
		},
		"disk": schema.Int64Attribute{
			Computed: true,
		},
		"public": schema.BoolAttribute{
			Optional:    true,
			Computed:    true,
			Default:     booldefault.StaticBool(false),
			Description: "Enable public network access for the VM.",
			PlanModifiers: []planmodifier.Bool{
				boolplanmodifier.RequiresReplace(),
			},
		},
		"interfaces": schema.ListNestedAttribute{
			Computed:    true,
			Description: "Network interfaces allocated by Kybornos.",
			NestedObject: schema.NestedAttributeObject{
				Attributes: map[string]schema.Attribute{
					"ip4": schema.StringAttribute{
						Computed: true,
					},
					"lladdr": schema.StringAttribute{
						Computed: true,
					},
					"primary": schema.BoolAttribute{
						Computed: true,
					},
					"public": schema.BoolAttribute{
						Computed: true,
					},
				},
			},
		},
	}}
}
func (r *VMResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	c, ok := req.ProviderData.(*client.Client)
	if !ok {
		resp.Diagnostics.AddError("Invalid provider data", "Expected *client.Client")
		return
	}
	r.c = c
}
func (r *VMResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var m vmModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &m)...)
	if resp.Diagnostics.HasError() {
		return
	}

	created, err := r.c.Create(
		ctx,
		m.Hostname.ValueString(),
		m.Size.ValueString(),
		m.Public.ValueBool(),
	)
	if err != nil {
		resp.Diagnostics.AddError("Create VM failed", err.Error())
		return
	}

	m.ID = types.StringValue(created.ID)
	m.VMName = types.StringNull()
	m.CPU = types.Int64Null()
	m.Memory = types.Int64Null()
	m.Disk = types.Int64Null()
	m.Interfaces = types.ListNull(interfaceObjectType)

	vm, err := r.c.Get(ctx, created.ID)
	if err != nil {
		resp.Diagnostics.AddWarning(
			"VM created but could not be read",
			err.Error(),
		)
	} else {
		m.VMName = types.StringValue(vm.VMName)
		m.CPU = types.Int64Value(vm.Size.CPU)
		m.Memory = types.Int64Value(vm.Size.Memory)
		m.Disk = types.Int64Value(vm.Size.Disk)
		interfaces, diags := interfacesToList(ctx, vm.Interfaces)
		resp.Diagnostics.Append(diags...)
		m.Interfaces = interfaces
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &m)...)
}
func (r *VMResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var m vmModel
	resp.Diagnostics.Append(req.State.Get(ctx, &m)...)
	if resp.Diagnostics.HasError() {
		return
	}
	vm, err := r.c.Get(ctx, m.ID.ValueString())
	if err != nil {
		var apiErr *client.Error
		if errors.As(err, &apiErr) && apiErr.Status == 404 {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Read VM failed", err.Error())
		return
	}
	if vm.ID == "" {
		resp.Diagnostics.AddError("Invalid VM response", "Missing VM id")
		return
	}
	m.Hostname = types.StringValue(vm.Hostname)
	m.ID = types.StringValue(vm.ID)
	m.VMName = types.StringValue(vm.VMName)
	m.Size = types.StringValue(vm.Size.Name)
	m.CPU = types.Int64Value(vm.Size.CPU)
	m.Memory = types.Int64Value(vm.Size.Memory)
	m.Disk = types.Int64Value(vm.Size.Disk)
	m.Public = types.BoolValue(vm.Public)
	interfaces, diags := interfacesToList(ctx, vm.Interfaces)
	resp.Diagnostics.Append(diags...)
	m.Interfaces = interfaces
	resp.Diagnostics.Append(resp.State.Set(ctx, &m)...)
}
func (r *VMResource) Update(_ context.Context, _ resource.UpdateRequest, resp *resource.UpdateResponse) {
	resp.Diagnostics.AddError("Unsupported VM update", "Changes to name or size require replacement.")
}
func (r *VMResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var m vmModel
	resp.Diagnostics.Append(req.State.Get(ctx, &m)...)
	if resp.Diagnostics.HasError() {
		return
	}
	err := r.c.Delete(ctx, m.ID.ValueString())
	if err != nil {
		var apiErr *client.Error
		if errors.As(err, &apiErr) && apiErr.Status == 404 {
			return
		}
		resp.Diagnostics.AddError("Delete VM failed", err.Error())
	}
}
func (r *VMResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
}
