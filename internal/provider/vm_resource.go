func (r *VMResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	c, ok := req.ProviderData.(*client.Client)
	if !ok {
		resp.Diagnostics.AddError("Invalid provider data", "Expected *client.Client")
		return
	}
	r.c = c
}
func (r *VMResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var m vmModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &m)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Extract optional autoinstall configuration.
	autoinstall := make(map[string]any)

	if !m.Autoinstall.IsNull() && !m.Autoinstall.IsUnknown() {
		var ai autoinstallModel

		resp.Diagnostics.Append(
			m.Autoinstall.As(ctx, &ai, basetypes.ObjectAsOptions{})...,
		)

		if resp.Diagnostics.HasError() {
			return
		}

		if !ai.Timezone.IsNull() && !ai.Timezone.IsUnknown() {
			autoinstall["timezone"] = ai.Timezone.ValueString()
		}
		if !ai.Username.IsNull() && !ai.Username.IsUnknown() {
			autoinstall["username"] = ai.Username.ValueString()
		}
		if !ai.HttpServer.IsNull() && !ai.HttpServer.IsUnknown() {
			autoinstall["http_server"] = ai.HttpServer.ValueString()
		}
		if !ai.ServerDir.IsNull() && !ai.ServerDir.IsUnknown() {
			autoinstall["server_directory"] = ai.ServerDir.ValueString()
		}
		if !ai.Sets.IsNull() && !ai.Sets.IsUnknown() {
			autoinstall["sets"] = ai.Sets.ValueString()
		}
	}

	var srvTags []map[string]any

	if !m.SrvTags.IsNull() && !m.SrvTags.IsUnknown() {
		var tags []srvTagModel

		resp.Diagnostics.Append(
			m.SrvTags.ElementsAs(ctx, &tags, false)...,
		)

		if resp.Diagnostics.HasError() {
			return
		}

		srvTags = make([]map[string]any, 0, len(tags))

		for _, tag := range tags {
			item := map[string]any{
				"name": tag.Name.ValueString(),
				"port": tag.Port.ValueInt64(),
			}

			if !tag.Weight.IsNull() {
				item["weight"] = tag.Weight.ValueInt64()
			}

			if !tag.Priority.IsNull() {
				item["priority"] = tag.Priority.ValueInt64()
			}

			if !tag.Protocol.IsNull() {
				item["protocol"] = tag.Protocol.ValueString()
			}

			if !tag.TTL.IsNull() {
				item["ttl"] = tag.TTL.ValueInt64()
			}

			if !tag.TLS.IsNull() {
				item["tls"] = tag.TLS.ValueBool()
			}

			if !tag.IngressDomain.IsNull() {
				item["ingress_domain"] = tag.IngressDomain.ValueString()
			}

			if !tag.AltNames.IsNull() {
				var altNames []string

				resp.Diagnostics.Append(
					tag.AltNames.ElementsAs(ctx, &altNames, false)...,
				)

				if resp.Diagnostics.HasError() {
					return
				}

				item["alt_names"] = altNames
			}

			srvTags = append(srvTags, item)
		}
	}

	created, err := r.c.Create(
		ctx,
		m.Hostname.ValueString(),
		m.Size.ValueString(),
		m.Public.ValueBool(),
		m.Encrypt.ValueString(),
		m.AutodiskTemplate.ValueBoolPointer(),
		autoinstall,
		srvTags,
	)
	if err != nil {
		resp.Diagnostics.AddError("Create VM failed", err.Error())
		return
	}

	m.ID = types.StringValue(created.ID)
	m.VMName = types.StringNull()
	m.CPU = types.Int64Null()
	m.Memory = types.Int64Null()
	m.Disk = types.Int64Null()
	m.Interfaces = types.ListNull(interfaceObjectType)

	vm, err := r.c.Get(ctx, created.ID)
	if err != nil {
		resp.Diagnostics.AddWarning(
			"VM created but could not be read",
			err.Error(),
		)
	} else {
		m.VMName = types.StringValue(vm.VMName)
		m.CPU = types.Int64Value(vm.Size.CPU)
		m.Memory = types.Int64Value(vm.Size.Memory)
		m.Disk = types.Int64Value(vm.Size.Disk)
		interfaces, diags := interfacesToList(ctx, vm.Interfaces)
		resp.Diagnostics.Append(diags...)
		m.Interfaces = interfaces
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &m)...)
}
func (r *VMResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var m vmModel
	resp.Diagnostics.Append(req.State.Get(ctx, &m)...)
	if resp.Diagnostics.HasError() {
		return
	}
	vm, err := r.c.Get(ctx, m.ID.ValueString())
	if err != nil {
		var apiErr *client.Error
		if errors.As(err, &apiErr) && apiErr.Status == 404 {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Read VM failed", err.Error())
		return
	}
	if vm.ID == "" {
		resp.Diagnostics.AddError("Invalid VM response", "Missing VM id")
		return
	}
	m.Hostname = types.StringValue(vm.Hostname)
	m.ID = types.StringValue(vm.ID)
	m.VMName = types.StringValue(vm.VMName)
	m.Size = types.StringValue(vm.Size.Name)
	m.CPU = types.Int64Value(vm.Size.CPU)
	m.Memory = types.Int64Value(vm.Size.Memory)
	m.Disk = types.Int64Value(vm.Size.Disk)
	m.Public = types.BoolValue(vm.Public)
	interfaces, diags := interfacesToList(ctx, vm.Interfaces)
	resp.Diagnostics.Append(diags...)
	m.Interfaces = interfaces
	resp.Diagnostics.Append(resp.State.Set(ctx, &m)...)
}
func (r *VMResource) Update(_ context.Context, _ resource.UpdateRequest, resp *resource.UpdateResponse) {
	resp.Diagnostics.AddError("Unsupported VM update", "Changes to name or size require replacement.")
}
func (r *VMResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var m vmModel
	resp.Diagnostics.Append(req.State.Get(ctx, &m)...)
	if resp.Diagnostics.HasError() {
		return
	}
	err := r.c.Delete(ctx, m.ID.ValueString())
	if err != nil {
		var apiErr *client.Error
		if errors.As(err, &apiErr) && apiErr.Status == 404 {
			return
		}
		resp.Diagnostics.AddError("Delete VM failed", err.Error())
	}
}
func (r *VMResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
}
